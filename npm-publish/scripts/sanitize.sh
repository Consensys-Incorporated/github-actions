# Yarn runs code from the repository: plugins listed in `.yarnrc.yml`, a
# `yarnPath` release, and lifecycle scripts during `yarn pack` and
# `yarn npm publish`. This script runs before any Yarn command that publishes,
# and removes the repository's ability to run code that way:
#
# 1. Yarn is pointed to a minimal configuration file, stored outside of the
#    checkout under a random name, so it cannot be shadowed by a file in the
#    repository. The repository's own `.yarnrc.yml` is never loaded. Its
#    name is the `yarn-rc-filename` step output, which action.yml passes to
#    the later steps that run Yarn as YARN_RC_FILENAME.
#    (YARN_IGNORE_PATH=1, set on every step, ignores `yarnPath`.)
# 2. The user-level `~/.yarnrc.yml` is removed: Yarn always loads it, and it
#    can also list plugins.
# 3. Lifecycle scripts are removed from every workspace, private ones included.
# 4. Packages that redirect publishing to a registry other than
#    `https://registry.npmjs.org` are rejected.

set -euo pipefail

if [[ "${RUNNER_DEBUG:-}" == "1" ]]; then
  set -x
fi

script_path="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"

# shellcheck source=SCRIPTDIR/environment.sh
source "$script_path/environment.sh"

rc_filename=".yarnrc-$(openssl rand -hex 16).yml"
rc_path="$(dirname "$PWD")/$rc_filename"
cat >"$rc_path" <<'EOF'
# Generated by Consensys-Incorporated/github-actions/npm-publish.
enableScripts: false
enableTelemetry: false
injectEnvironmentFiles: []
nodeLinker: node-modules
npmPublishRegistry: "https://registry.npmjs.org"
npmRegistryServer: "https://registry.npmjs.org"
EOF

export YARN_RC_FILENAME="$rc_filename"

# Passed to the action's later Yarn steps as a step output, not through
# $GITHUB_ENV, so the caller's later steps keep their own Yarn configuration.
if [[ -n "${GITHUB_OUTPUT:-}" ]]; then
  echo "yarn-rc-filename=$rc_filename" >>"$GITHUB_OUTPUT"
fi

rm -f "$HOME/.yarnrc.yml"

# The workspace list is read with the configuration above, so no code from the
# repository is loaded. In a polyrepo, the root is the only workspace. Private
# workspaces are included: they aren't published, but their lifecycle scripts
# are removed anyway.
locations="$(
  yarn workspaces list --json | jq --raw-output '
    .location |
    if test("[[:cntrl:]]") then
      "::error::A workspace location contains a control character.\n" | halt_error(1)
    else . end
  '
)"

while IFS= read -r location; do
  [[ -z "$location" ]] && continue

  manifest="$location/package.json"

  # As JSON, so that it prints on one line.
  registry="$(jq --compact-output 'if .private == true then empty else .publishConfig.registry // empty end' "$manifest")"
  if [[ -n "$registry" && "$registry" != '"https://registry.npmjs.org"' && "$registry" != '"https://registry.npmjs.org/"' ]]; then
    echo "::error::\"$manifest\" sets \"publishConfig.registry\" to $registry. Only \"https://registry.npmjs.org\" is supported."
    exit 1
  fi

  sanitized="$(jq 'del(.scripts.prepublish, .scripts.prepublishOnly, .scripts.prepack, .scripts.postpack)' "$manifest")"
  echo "$sanitized" >"$manifest"
done <<<"$locations"

echo "Yarn configuration and lifecycle scripts sanitized."
